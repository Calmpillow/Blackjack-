"use strict";
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
const js = fs.readFileSync(path.join(root, "game.js"), "utf8");
const server = fs.readFileSync(path.join(__dirname, "server.js"), "utf8");
const pkg = JSON.parse(fs.readFileSync(path.join(__dirname, "package.json"), "utf8"));
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
const duplicates = ids.filter((id, i) => ids.indexOf(id) !== i);
if (duplicates.length) throw new Error("Duplicate HTML ids: " + [...new Set(duplicates)].join(", "));
const idSet = new Set(ids);
const refs = [...js.matchAll(/\$\("([^"]+)"\)/g)].map(m => m[1]);
const missing = [...new Set(refs.filter(id => !idSet.has(id)))];
if (missing.length) throw new Error("JavaScript references missing HTML ids: " + missing.join(", "));
for (const id of ["roomList", "privateRoom", "roomPassword", "refreshRooms", "loadingScreen", "choosePhotoBtn", "avatarFile"]) if (!idSet.has(id)) throw new Error("Required UI element missing: " + id);
if (pkg.dependencies && Object.keys(pkg.dependencies).length) throw new Error("Server must not depend on external packages.");
for (const feature of ["/health", "/api/rooms", "server.on(\"upgrade\"", "type === \"host\"", "type === \"join\"", "type === \"host-state\""]) if (!server.includes(feature)) throw new Error("Server feature missing: " + feature);
if (!js.includes("new WebSocket(wsUrl())") || !html.includes("config.js") || !html.includes("game.js")) throw new Error("Frontend multiplayer scripts are not linked.");
console.log(`Static validation passed: ${ids.length} unique HTML IDs; ${new Set(refs).size} JavaScript element references; gallery picker and dependency-free multiplayer server found.`);
